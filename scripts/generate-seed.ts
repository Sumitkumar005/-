// Regenerates supabase/seed.sql from src/lib/seed/demo-suppliers.ts.
// Run: npx tsx scripts/generate-seed.ts

import { writeFileSync } from "node:fs";
import { demoSuppliers } from "../src/lib/seed/demo-suppliers";

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `array[${v.map(lit).join(", ")}]::text[]`;
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const rows = demoSuppliers();
const cols = Object.keys(rows[0]);
const sql = [
  "-- Demo supplier network (Delhi NCR). Generated by scripts/generate-seed.ts. Safe to re-run.",
  "-- These are fictional businesses with unallocated phone numbers; real calls to them are refused.",
  `insert into public.suppliers (${cols.join(", ")}) values`,
  rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n"),
  "on conflict (phone) where phone is not null do nothing;",
  "",
].join("\n");

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${rows.length} demo suppliers to supabase/seed.sql`);
